inline void Require(bool ok, const char* why) {
    if (!ok) throw std::runtime_error(why);
}
inline uint32_t Word(ArmCpu* cpu, uint32_t address) {
    uint32_t value;
    Require(cpuInspectRead(cpu, address, &value, 4), "TG50 unmapped context word");
    return value;
}
inline uint32_t BigWord(ArmCpu* cpu, uint32_t address) {
    uint8_t bytes[4];
    Require(cpuInspectRead(cpu, address, bytes, 4), "TG50 unmapped 68k context word");
    return uint32_t(bytes[0]) << 24 | uint32_t(bytes[1]) << 16 |
           uint32_t(bytes[2]) << 8 | bytes[3];
}
inline uint8_t Byte(ArmCpu* cpu, uint32_t address) {
    uint8_t value;
    Require(cpuInspectRead(cpu, address, &value, 1), "TG50 unmapped context byte");
    return value;
}
inline uint32_t Pointer(ArmCpu* cpu, uint32_t address, uint32_t bytes) {
    uint32_t value = Word(cpu, address);
    Require(value && !(value & 3) && cpuInspectRamRange(cpu, value, bytes),
            "TG50 invalid context pointer");
    return value;
}
struct Range {
    uint32_t first{}, last{};
    bool Contains(uint32_t address, uint32_t bytes) const {
        return bytes && address >= first && uint64_t(address) + bytes <= uint64_t(last) + 1;
    }
    void Validate(ArmCpu* cpu) const {
        Require(first && !(first & 3) && first < last &&
                uint64_t(last) - first < 16 * 1024 * 1024 &&
                cpuInspectWritableRamRange(cpu, first, last - first + 1, false), "TG50 invalid owned stack");
    }
    bool operator==(const Range& r) const { return first == r.first && last == r.last; }
};

