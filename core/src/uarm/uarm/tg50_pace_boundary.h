struct Boundary {
    uint32_t r9{}, root{}, kernel{}, task{}, tls{}, app{}, state{}, paceRoot{};
    uint32_t frameSp{}, entryVa{}, m68kSp{};
    Range armStack, m68kStack;
    std::array<uint32_t, 10> frame{};

    static Boundary Capture(SoC& soc, bool event) {
        Require(soc.GetDeviceType() == DeviceType5::deviceTypeTG50 &&
                soc.PrepareM68kSupport(), "TG50 interpreter descriptor unavailable");
        auto* cpu = soc.GetCpu();
        Require(cpuIsModePace(cpu) && !cpuIsThumb(cpu) &&
                (cpuGetRegExternal(cpu, ARM_REG_NUM_CPSR) & 0xff) == 0x10,
                "TG50 interpreter is not active in the app");
        auto* r = cpuGetRegisters(cpu);
        const auto pace = paceDebugState();
        Boundary b;
        b.r9 = r[9];
        Require(b.r9 >= 16 && !(b.r9 & 3) && cpuInspectRamRange(cpu, b.r9 - 16, 20),
                "TG50 invalid interpreter r9");
        b.root = Pointer(cpu, b.r9, 0x100);
        Require(Word(cpu, b.root + 4) == b.r9, "TG50 canonical r9 link changed");
        const uint32_t kernelRoot = Pointer(cpu, b.root, 0xb0);
        b.kernel = Pointer(cpu, kernelRoot + 0xac, 0x2200);
        Require(Byte(cpu, b.kernel + 0x21d0) != 4, "TG50 current task is unavailable");
        b.task = Pointer(cpu, b.kernel + 0x21c4, 144);
        Require(b.task >= b.kernel && b.task - b.kernel < 32 * 144 &&
                (b.task - b.kernel) % 144 == 0 && Byte(cpu, b.task + 25),
                "TG50 invalid current task");
        const uint32_t reserved = Pointer(cpu, b.task, 8);
        b.tls = Pointer(cpu, reserved, 8);
        uint32_t child = Pointer(cpu, b.tls + 4, 64);
        b.app = Word(cpu, child + 60);
        if (b.app) {
            Require(!(b.app & 3) && cpuInspectRamRange(cpu, b.app, 64),
                    "TG50 invalid root app context");
        } else b.app = child;
        b.state = Pointer(cpu, b.app + 12, 404);
        Require(pace.statePtr == b.state && r[0] == b.state,
                "TG50 current task does not own the interpreter state");
        b.paceRoot = Pointer(cpu, b.state + 0xcc, 404);
        b.armStack = {Word(cpu, b.app + 0x18), Word(cpu, b.app + 0x34)};
        b.m68kStack = {BigWord(cpu, b.state + 0x94), BigWord(cpu, b.state + 0xac)};
        b.armStack.Validate(cpu);
        b.m68kStack.Validate(cpu);
        Require(b.armStack.last < b.m68kStack.first || b.m68kStack.last < b.armStack.first,
                "TG50 app stacks overlap");
        b.frameSp = r[13];
        b.m68kSp = pace.a[7];
        Require(!(b.frameSp & 3) && b.armStack.Contains(b.frameSp, sizeof(b.frame)) &&
                !(b.m68kSp & 1) && b.m68kStack.Contains(b.m68kSp, 4),
                "TG50 active interpreter stack is outside its app");
        Require(cpuInspectRead(cpu, b.frameSp, b.frame.data(), sizeof(b.frame)) &&
                b.frame[0] == b.state && b.frame[1] == b.state && b.frame[6] == b.r9 &&
                Word(cpu, b.state + 0x74) == b.frameSp + 40,
                "TG50 interpreter frame does not match its state");
        Require(r[15] >= 4, "TG50 invalid interpreter entry");
        b.entryVa = r[15] - 4;
        PacePatch descriptor{};
        const Buffer rom = soc.GetRomData();
        Require(pacePatchDiscoverTg50(&descriptor, 0, rom.data, rom.size),
                "TG50 original interpreter layout changed");
        const auto mapping = mmuTranslateInspect(cpuGetMMU(cpu), b.entryVa, false);
        Require(MMU_TRANSLATE_RESULT_OK(mapping) &&
                MMU_TRANSLATE_RESULT_PA(mapping) == descriptor.enterPace &&
                b.frame[9] == b.entryVa + 0x6404,
                "TG50 interpreter mapping or return changed");
        const uint32_t table = Pointer(cpu, b.r9 - 8, 0x838);
        const uint32_t kal = Pointer(cpu, b.r9 - 4, 0x284);
        Require(Word(cpu, table + 0x834) == 0x2005ecbc &&
                Word(cpu, kal + 0x27c) == 0x200209d8 &&
                Word(cpu, kal + 0x280) == 0x200209dc,
                "TG50 context dispatch tables changed");
        if (event) {
            Require(child == b.app && (Word(cpu, b.app) & 0xffff) == 0 &&
                    (Word(cpu, b.app + 8) & 0x1e) == 0x0e,
                    "TG50 event does not belong to the root UI app");
            uint8_t instruction[4];
            static const uint8_t getEvent[] = {0x4e, 0x4f, 0xa1, 0x1d};
            Require(cpuInspectRead(cpu, pace.pc, instruction, 4) &&
                    !memcmp(instruction, getEvent, 4) &&
                    b.m68kStack.Contains(b.m68kSp, 8),
                    "TG50 app is not at its event syscall");
        }
        return b;
    }

    bool SameOwner(const Boundary& b) const {
        return r9 == b.r9 && root == b.root && kernel == b.kernel && task == b.task &&
               tls == b.tls && app == b.app && state == b.state && paceRoot == b.paceRoot &&
               armStack == b.armStack && m68kStack == b.m68kStack && entryVa == b.entryVa;
    }
};
