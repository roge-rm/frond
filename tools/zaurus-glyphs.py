#!/usr/bin/env python3
"""Writes core/src/uarm/native/ZaurusGlyphs.h: the Japanese characters printed on the Zaurus
SL-C3000 keyboard as 64x64 one-bit bitmaps of their em square, from Noto Sans CJK JP Medium
(SIL OFL 1.1, see licences/noto-sans-cjk-OFL). Needs Pillow with FreeType.

    tools/zaurus-glyphs.py [path to NotoSansCJK-Medium.ttc]
"""
import pathlib
import sys

from PIL import Image, ImageDraw, ImageFont

# Every non-ASCII character the art prints, in code point order.
CHARS = sorted(set('カナひら全半前候補変換、。あアｱ「」¥記号漢字音訓'))
GRID = 64
OVERSAMPLE = 4
# Noto Sans CJK's ideographic em box runs from 0.88 em above the baseline to 0.12 below.
ASCENT = 0.88


def bitmap(font, char):
    size = GRID * OVERSAMPLE
    image = Image.new('L', (size, size), 0)
    ImageDraw.Draw(image).text((0, ASCENT * size), char, font=font, fill=255, anchor='ls')
    small = image.resize((GRID, GRID), Image.BOX)
    return [[small.getpixel((x, y)) >= 128 for x in range(GRID)] for y in range(GRID)]


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/fonts/opentype/noto/NotoSansCJK-Medium.ttc'
    font = ImageFont.truetype(path, GRID * OVERSAMPLE, index=0)
    assert font.getname()[0] == 'Noto Sans CJK JP', font.getname()
    lines = [
        '// Generated by tools/zaurus-glyphs.py from Noto Sans CJK JP Medium. Do not edit.',
        '// Copyright 2014-2021 Adobe (http://www.adobe.com/). Noto is a trademark of Google Inc.',
        '// SIL Open Font License 1.1, see licences/noto-sans-cjk-OFL.',
        '#ifndef FROND_ZAURUS_GLYPHS_H',
        '#define FROND_ZAURUS_GLYPHS_H',
        '#include <cstdint>',
        '',
        '// A character as a %dx%d bitmap of its em square, row by row from the top, each row %d hex'
        % (GRID, GRID, GRID // 4),
        '// digits with the most significant bit leftmost. The baseline is %.2f em down; advance is in' % ASCENT,
        '// 64ths of an em.',
        'struct ZaurusGlyph { uint32_t code; int advance; const char* rows; };',
        'constexpr int zaurusGlyphGrid=%d;' % GRID,
        'constexpr float zaurusGlyphAscent=%.2ff;' % ASCENT,
        'inline const ZaurusGlyph zaurusGlyphs[]={',
    ]
    for char in CHARS:
        rows = bitmap(font, char)
        advance = round(font.getlength(char) / OVERSAMPLE)
        hexrows = ''.join('%0*x' % (GRID // 4, int(''.join('1' if b else '0' for b in row), 2)) for row in rows)
        lines.append('    {0x%04x,%d,  // %s' % (ord(char), advance, char))
        for i in range(0, len(hexrows), 128):
            lines.append('     "%s"' % hexrows[i:i + 128])
        lines[-1] += '},'
    lines += ['};', '#endif', '']
    out = pathlib.Path(__file__).resolve().parent.parent / 'core/src/uarm/native/ZaurusGlyphs.h'
    out.write_text('\n'.join(lines), encoding='utf-8')
    print('%s: %d glyphs, %d bytes' % (out, len(CHARS), out.stat().st_size))


if __name__ == '__main__':
    main()
