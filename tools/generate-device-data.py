#!/usr/bin/env python3
"""Export deviceProfiles5 for Python and Android. Run after make prepare; --check refuses stale files."""
import argparse
import json
import os
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
# Devices the desktop runs that the Android app has no controls for yet. They stay out of its list.
DESKTOP_ONLY = {'tapwave-zodiac-2'}


def outputs(profiles):
    available = [p for p in profiles['profiles'] if p['available'] and p['name'] not in DESKTOP_ONLY]
    fields = {
        'id': 'name', 'label': 'display_name', 'norSize': 'nor_bytes', 'nandSize': 'raw_nand_bytes',
        'nandRequired': 'explicit_raw_nand', 'fastAudioNorMd5': 'fast_audio_md5',
        'sound': 'sound', 'storageSlot': 'storage_slot', 'sdSlot': 'sd_slot', 'memoryStick': 'memory_stick_supported', 'network': 'network', 'serialPort': 'serial', 'microphone': 'microphone', 'camera': 'camera',
        'keyboard': 'keyboard', 'usb': 'usb', 'infrared': 'infrared', 'bluetooth': 'bluetooth', 'modem': 'modem', 'irPhone': 'ir_phone', 'usbPrinter': 'usb_printer', 'usbWifi': 'usb_wifi', 'builtInWifi': 'built_in_wifi',
        'detectKind': 'detect', 'companyId': 'company_id', 'halId': 'hal_id',
        'norLayout': 'nor_layout', 'headerOffset': 'header_offset', 'bigCardOffset': 'big_card_offset',
        'width': 'width', 'height': 'height', 'sideTabWidth': 'side_tab_width', 'silkscreenHeight': 'silkscreen_height',
        'appNamesText': 'app_names', 'buttonsText': 'buttons', 'holdPresent': 'hold_present', 'holdSupported': 'hold_supported', 'homeKey': 'home_key', 'homeX': 'home_x', 'homeY': 'home_y',
        'menuX': 'menu_x', 'menuY': 'menu_y', 'rotatingStatusBar': 'rotating_status_bar',
        'sdMin': 'sd_min_bytes', 'sdMax': 'sd_max_bytes', 'msSizes': 'ms_sizes_mb', 'msProMax': 'ms_pro_max_mb',
        'runs68k': 'runs_68k', 'hotSyncButton': 'hot_sync_button',
    }
    longs = {'norSize', 'nandSize', 'companyId', 'halId', 'headerOffset', 'bigCardOffset', 'sdMin', 'sdMax'}
    def literal(key, value):
        if key == 'fastAudioNorMd5' and not value:
            return 'null'
        if key == 'msSizes':
            return 'listOf(' + ', '.join(map(str, value)) + ')'
        if key == 'sdMax':
            value = min(value, (1 << 63) - 1)
        # 68k ROMs have no one size; the header says which device a ROM is for.
        if key == 'norSize' and value is None:
            value = 0
        return json.dumps(value, ensure_ascii=False) + ('L' if key in longs else '')
    kotlin = '// Generated by tools/generate-device-data.py from deviceProfiles5.\npackage com.rm.frond\n\n'
    kotlin += 'internal val deviceInventory = listOf(\n'
    for profile in available:
        kotlin += '    Device(\n'
        for key, source in fields.items():
            kotlin += f'        {key} = {literal(key, profile[source])},\n'
        slots = profile.get('storage_slots', [])
        if slots:
            kotlin += '        storageSlots = listOf(\n'
            for slot in slots:
                kotlin += f'            StorageSlot({slot["id"]}, {slot["label"]}, {json.dumps(slot["kind"])}, listOf(\n'
                for family in slot.get('media_families', []):
                    sizes = lambda key: 'listOf(' + ', '.join(str(n) + 'L' for n in family.get(key, [])) + ')'
                    kotlin += (f'                CardFamily({json.dumps(family["family"])}, '
                               f'{family["min_bytes"]}L, {min(family["max_bytes"], (1 << 63) - 1)}L, '
                               f'{json.dumps(family["size_rule"])}, {sizes("runtime_sizes_bytes")}, '
                               f'{sizes("guest_qualified_sizes_bytes")}),\n')
                kotlin += '            )),\n'
            kotlin += '        ),\n'
        variants = profile.get('firmware_variants', [])
        if variants:
            kotlin += '        firmwareVariants = listOf(\n'
            for variant in variants:
                kotlin += '            FirmwareVariant(\n'
                for key, source in {
                    'id': 'id', 'norSize': 'nor_bytes', 'headerOffset': 'header_offset',
                    'cardName': 'card_name', 'manufacturer': 'manufacturer',
                    'companyId': 'company_id', 'halId': 'hal_id',
                    'cardEndsAtEof': 'card_ends_at_eof', 'fastAudioNorMd5': 'fast_audio_md5',
                    'powerSupported': 'power_supported',
                }.items():
                    kotlin += f'                {key} = {literal(key, variant[source])},\n'
                kotlin += '            ),\n'
            kotlin += '        ),\n'
        kotlin += '    ),\n'
    kotlin += ')\n'
    return {
        ROOT / 'tools/device-profiles.json': json.dumps(profiles, ensure_ascii=False, indent=2) + '\n',
        ROOT / 'android/app/src/main/kotlin/com/rm/frond/DeviceInventory.kt': kotlin,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--source', type=Path, default=ROOT / 'build/source', help='prepared native source root')
    parser.add_argument('--build-dir', type=Path, default=ROOT / 'build/device-data', help='exporter build folder')
    args = parser.parse_args()
    work = args.build_dir.absolute()
    work.mkdir(parents=True, exist_ok=True)
    exporter = work / 'export'
    subprocess.run([os.environ.get('CXX', 'c++'), '-std=c++17', '-O0',
                    '-I' + str(args.source.absolute() / 'src/common'), str(ROOT / 'tools/device-profiles.cpp'),
                    '-o', str(exporter)], check=True)
    profiles = json.loads(subprocess.check_output([str(exporter)], text=True))
    stale = []
    for path, data in outputs(profiles).items():
        if args.check:
            if not path.is_file() or path.read_text() != data:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(data)
    if stale:
        parser.exit(1, 'Stale device data: ' + ', '.join(stale) + '\nRun tools/generate-device-data.py after make prepare.\n')


if __name__ == '__main__':
    main()
