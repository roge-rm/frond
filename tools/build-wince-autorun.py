#!/usr/bin/env python3
"""Rebuild the Windows CE ARMv4T SD autorun helper with LLVM 19."""
import argparse
from pathlib import Path
import struct
import subprocess
from tempfile import TemporaryDirectory


ROOT = Path(__file__).resolve().parents[1]
IMPORTS = {
    "CopyFileW": 164,
    "DeleteFileW": 165,
    "CreateProcessW": 493,
    "WaitForSingleObject": 497,
    "GetLastError": 516,
    "GetTickCount": 535,
    "CloseHandle": 553,
    "GetCommandLineW": 1231,
}
ELF_DIRECTIVES = {
    ".addrsig", ".addrsig_sym", ".cantunwind", ".code", ".cpu", ".eabi_attribute",
    ".file", ".fnend", ".fnstart", ".ident", ".local", ".pad", ".save", ".setfp",
    ".size", ".type",
}


def coff_assembly(assembly):
    # Compile for Thumb-1 with the bare-metal target. The Windows target requires Thumb-2.
    out = [".thumb"]
    for line in assembly.splitlines():
        parts = line.strip().split(maxsplit=1)
        if not parts or parts[0] in ELF_DIRECTIVES:
            continue
        if parts[0] == ".section":
            section = parts[1].split(",", 1)[0]
            if section.startswith(".rodata"):
                out.append('.section .rdata,"dr"')
            elif section.startswith(".data"):
                out.append(".data")
            elif section != '".note.GNU-stack"':
                raise ValueError(f"Unexpected section {section}")
        elif parts[0] == ".comm":
            name, size, alignment = parts[1].split(",")
            out.extend((".bss", f".balign {alignment}", f"{name}:", f".zero {size}"))
        else:
            out.append(line)
    return "\n".join(out) + "\n"


def build(tmp):
    def run(*args):
        subprocess.run(args, cwd=tmp, check=True)

    run("clang-19", "--target=thumbv4t-none-eabi", "-mcpu=arm920t", "-mthumb",
        "-ffreestanding", "-fshort-wchar", "-fno-stack-protector", "-fno-unwind-tables",
        "-Oz", "-Wall", "-Wextra", "-Werror", "-S", str(ROOT / "tools/wince-autorun.c"),
        "-o", "autorun-elf.s")
    (tmp / "autorun.s").write_text(coff_assembly((tmp / "autorun-elf.s").read_text()))
    run("clang-19", "--target=armv7-pc-windows-msvc", "-c", "autorun.s", "-o", "autorun.obj")
    exports = "".join(f"    {name} @{ordinal} NONAME\n" for name, ordinal in IMPORTS.items())
    (tmp / "coredll.def").write_text("LIBRARY coredll.dll\nEXPORTS\n" + exports)
    run("llvm-dlltool-19", "-m", "arm", "-d", "coredll.def", "-l", "coredll.lib")
    (tmp / "aygshell.def").write_text("LIBRARY aygshell.dll\nEXPORTS\n    SHGetAutoRunPath @90 NONAME\n")
    run("llvm-dlltool-19", "-m", "arm", "-d", "aygshell.def", "-l", "aygshell.lib")
    run("lld-link-19", "/machine:arm", "/entry:autorun", "/subsystem:windows,4.0",
        "/nodefaultlib", "/timestamp:0", "/out:autorun.exe", "autorun.obj", "coredll.lib", "aygshell.lib")

    # LLD uses the desktop ARMNT machine and Windows GUI subsystem. CE has its own IDs.
    image = bytearray((tmp / "autorun.exe").read_bytes())
    header, = struct.unpack_from("<I", image, 60)
    if image[header:header + 6] != b"PE\0\0\xc4\x01":
        raise ValueError("Expected an ARMNT PE image")
    struct.pack_into("<H", image, header + 4, 0x1C2)
    optional = header + 24
    struct.pack_into("<HHI", image, optional + 68, 9, 0, 65536)
    return image


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    with TemporaryDirectory(prefix="frond-wince-") as directory:
        image = build(Path(directory))
    if args.output.suffix == ".exe":
        args.output.write_bytes(image)
        return
    rows = ["    " + ", ".join(f"0x{byte:02x}" for byte in image[i:i + 16]) + ","
            for i in range(0, len(image), 16)]
    args.output.write_text("// Generated by tools/build-wince-autorun.py.\n"
                           "#ifndef FROND_WINCE_AUTORUN_DATA_H\n"
                           "#define FROND_WINCE_AUTORUN_DATA_H\n\n"
                           "namespace frondNative {\n"
                           "inline constexpr unsigned char winCeAutorun[] = {\n"
                           + "\n".join(rows) +
                           "\n};\n}  // namespace frondNative\n#endif\n")


if __name__ == "__main__":
    main()
